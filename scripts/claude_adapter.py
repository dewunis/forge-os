#!/usr/bin/env python3
"""Generate or verify the Claude Code adapter from canonical ForgeOS sources."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys
import tomllib


ROOT = Path(__file__).resolve().parent.parent
CODEX_AGENTS = ROOT / ".codex" / "agents"
SHARED_SKILLS = ROOT / ".agents" / "skills"
CLAUDE_AGENTS = ROOT / ".claude" / "agents"
CLAUDE_SKILLS = ROOT / ".claude" / "skills"
GENERATED_NOTICE = "<!-- Generated by scripts/claude_adapter.py; do not edit directly. -->"
SKILL_REFERENCE = re.compile(r"\.agents/skills/([a-z0-9-]+)/SKILL\.md")


def canonical_agent_files() -> list[Path]:
    return sorted(CODEX_AGENTS.glob("*.toml"))


def canonical_skill_directories() -> list[Path]:
    return sorted(path for path in SHARED_SKILLS.iterdir() if path.is_dir())


def render_agent(source: Path) -> str:
    data = tomllib.loads(source.read_text(encoding="utf-8"))
    name = source.stem
    description = data["description"]
    instructions = data["developer_instructions"].strip()
    skills = sorted(set(SKILL_REFERENCE.findall(instructions)))

    lines = [
        "---",
        f"name: {name}",
        f"description: {json.dumps(description, ensure_ascii=False)}",
    ]
    if skills:
        lines.append("skills:")
        lines.extend(f"  - {skill}" for skill in skills)
    lines.extend(
        [
            "---",
            "",
            GENERATED_NOTICE,
            f"Canonical role source: `.codex/agents/{source.name}`.",
            "",
            instructions,
            "",
        ]
    )
    return "\n".join(lines)


def expected_agents() -> dict[Path, bytes]:
    return {
        CLAUDE_AGENTS / f"{source.stem}.md": render_agent(source).encode("utf-8")
        for source in canonical_agent_files()
    }


def expected_skills() -> dict[Path, bytes]:
    expected: dict[Path, bytes] = {}
    for source_dir in canonical_skill_directories():
        for source in sorted(path for path in source_dir.rglob("*") if path.is_file()):
            relative = source.relative_to(SHARED_SKILLS)
            expected[CLAUDE_SKILLS / relative] = source.read_bytes()
    return expected


def actual_files(root: Path) -> set[Path]:
    if not root.exists():
        return set()
    return {path for path in root.rglob("*") if path.is_file()}


def check_tree(expected: dict[Path, bytes], root: Path, label: str) -> list[str]:
    problems: list[str] = []
    actual = actual_files(root)
    expected_paths = set(expected)
    for missing in sorted(expected_paths - actual):
        problems.append(f"missing {label}: {missing.relative_to(ROOT)}")
    for extra in sorted(actual - expected_paths):
        problems.append(f"unexpected {label}: {extra.relative_to(ROOT)}")
    for path in sorted(actual & expected_paths):
        if path.read_bytes() != expected[path]:
            problems.append(f"stale {label}: {path.relative_to(ROOT)}")
    return problems


def remove_unexpected(root: Path, expected_paths: set[Path]) -> None:
    for path in sorted(actual_files(root) - expected_paths, reverse=True):
        path.unlink()
    if root.exists():
        for directory in sorted(
            (path for path in root.rglob("*") if path.is_dir()),
            key=lambda path: len(path.parts),
            reverse=True,
        ):
            try:
                directory.rmdir()
            except OSError:
                pass


def synchronize() -> None:
    agents = expected_agents()
    skills = expected_skills()
    for path, content in {**agents, **skills}.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_bytes() != content:
            path.write_bytes(content)
    remove_unexpected(CLAUDE_AGENTS, set(agents))
    remove_unexpected(CLAUDE_SKILLS, set(skills))
    print(f"SYNCED: {len(agents)} Claude agents and {len(canonical_skill_directories())} Skills.")


def verify() -> int:
    problems = check_tree(expected_agents(), CLAUDE_AGENTS, "agent")
    problems.extend(check_tree(expected_skills(), CLAUDE_SKILLS, "Skill file"))
    if problems:
        for problem in problems:
            print(f"ERROR: {problem}", file=sys.stderr)
        print("Run: python scripts/claude_adapter.py", file=sys.stderr)
        return 1
    print(
        f"PASS: Claude adapter matches {len(canonical_agent_files())} canonical agents "
        f"and {len(canonical_skill_directories())} canonical Skills."
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify without writing")
    args = parser.parse_args()
    if args.check:
        return verify()
    synchronize()
    return verify()


if __name__ == "__main__":
    raise SystemExit(main())
