#!/usr/bin/env python3
"""Generate or verify the Gemini CLI and Antigravity adapters from canonical ForgeOS sources."""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import sys
import tempfile
import tomllib


ROOT = Path(__file__).resolve().parent.parent
CODEX_AGENTS = ROOT / ".codex" / "agents"
SHARED_SKILLS = ROOT / ".agents" / "skills"
AGENTS_MANIFEST = ROOT / ".agents" / "agents.json"
GEMINI_AGENTS = ROOT / ".gemini" / "agents"
ANTIGRAVITY_AGENTS = ROOT / ".gemini" / "antigravity-agents"
GEMINI_SKILLS = ROOT / ".gemini" / "skills"
GENERATED_NOTICE = "<!-- Generated by scripts/gemini_adapter.py; do not edit directly. -->"
SKILL_REFERENCE = re.compile(r"\.agents/skills/([a-z0-9-]+)/SKILL\.md")

READ_ONLY_AGENTS = frozenset(
    {
        "code-reviewer",
        "product-manager",
        "security-engineer",
        "software-architect",
        "tech-lead",
        "ui-ux-designer",
    }
)
READ_WRITE_AGENTS = frozenset(
    {
        "ai-llm-engineer",
        "backend-engineer",
        "database-engineer",
        "frontend-engineer",
        "mobile-engineer",
        "performance-engineer",
        "platform-engineer",
        "qa-engineer",
        "release-manager",
        "reliability-engineer",
        "technical-writer",
    }
)

GEMINI_CLI_READ_ONLY_TOOLS = (
    "read_file",
    "read_many_files",
    "list_directory",
    "glob",
    "grep_search",
    "run_shell_command",
    "google_web_search",
    "web_fetch",
    "activate_skill",
)
GEMINI_CLI_READ_WRITE_TOOLS = (
    "read_file",
    "read_many_files",
    "list_directory",
    "glob",
    "grep_search",
    "replace",
    "write_file",
    "run_shell_command",
    "google_web_search",
    "web_fetch",
    "activate_skill",
)
ANTIGRAVITY_READ_ONLY_TOOLS = (
    "read_file",
    "run_command",
    "manage_task",
    "search_web",
)
ANTIGRAVITY_READ_WRITE_TOOLS = (
    "read_file",
    "edit_file",
    "write_file",
    "run_command",
    "manage_task",
    "search_web",
)


def is_read_only_agent(name: str) -> bool:
    """Return whether a canonical role name is read-only or raise for invalid classification."""
    overlap = READ_ONLY_AGENTS & READ_WRITE_AGENTS
    if overlap:
        raise ValueError(
            f"Agent roles classified as both read-only and read-write: {sorted(overlap)}"
        )
    if name in READ_ONLY_AGENTS:
        return True
    if name in READ_WRITE_AGENTS:
        return False
    raise ValueError(f"Unclassified agent role: {name}")


def canonical_agent_files() -> list[Path]:
    return sorted(CODEX_AGENTS.glob("*.toml"))


def canonical_skill_directories() -> list[Path]:
    return sorted(path for path in SHARED_SKILLS.iterdir() if path.is_dir())


def _render_markdown_agent(
    source: Path,
    *,
    tools: tuple[str, ...],
    extra_frontmatter: list[str] | None = None,
) -> str:
    data = tomllib.loads(source.read_text(encoding="utf-8"))
    name = source.stem
    description = data["description"]
    instructions = data["developer_instructions"].strip()
    lines = [
        "---",
        f"name: {name}",
        f"description: {json.dumps(description, ensure_ascii=False)}",
        *(extra_frontmatter or []),
        "tools:",
        *(f"  - {tool}" for tool in tools),
        "---",
        "",
        GENERATED_NOTICE,
        f"Canonical role source: `.codex/agents/{source.name}`.",
        "",
        instructions,
        "",
    ]
    return "\n".join(lines)


def render_gemini_cli_agent(source: Path) -> str:
    """Render a Gemini CLI compatible agent markdown file."""
    tools = (
        GEMINI_CLI_READ_ONLY_TOOLS
        if is_read_only_agent(source.stem)
        else GEMINI_CLI_READ_WRITE_TOOLS
    )
    return _render_markdown_agent(source, tools=tools)


def render_antigravity_agent(source: Path) -> str:
    """Render a native Antigravity subagent markdown file."""
    data = tomllib.loads(source.read_text(encoding="utf-8"))
    instructions = data["developer_instructions"].strip()
    skills = sorted(set(SKILL_REFERENCE.findall(instructions)))
    tools = (
        ANTIGRAVITY_READ_ONLY_TOOLS
        if is_read_only_agent(source.stem)
        else ANTIGRAVITY_READ_WRITE_TOOLS
    )
    extra_frontmatter = ["subagent: true", "mainAgent: false"]
    if skills:
        extra_frontmatter.append("skills:")
        extra_frontmatter.extend(f"  - ../skills/{skill}" for skill in skills)
    return _render_markdown_agent(
        source,
        tools=tools,
        extra_frontmatter=extra_frontmatter,
    )


render_agent = render_antigravity_agent


def expected_agents_manifest() -> bytes:
    payload = {"entries": [{"path": ".gemini/antigravity-agents"}]}
    return (json.dumps(payload, indent=2) + "\n").encode("utf-8")


def expected_agents() -> dict[Path, bytes]:
    return {
        GEMINI_AGENTS / f"{source.stem}.md": render_gemini_cli_agent(source).encode("utf-8")
        for source in canonical_agent_files()
    }


def expected_antigravity_agents() -> dict[Path, bytes]:
    return {
        ANTIGRAVITY_AGENTS / f"{source.stem}.md": render_antigravity_agent(source).encode("utf-8")
        for source in canonical_agent_files()
    }


def expected_skills() -> dict[Path, bytes]:
    expected: dict[Path, bytes] = {}
    for source_dir in canonical_skill_directories():
        if source_dir.is_symlink():
            raise ValueError(f"Symlink not allowed in canonical skills: {source_dir}")
        for source in sorted(source_dir.rglob("*")):
            if source.is_symlink():
                raise ValueError(f"Symlink not allowed in canonical skills: {source}")
            if source.is_file():
                relative = source.relative_to(SHARED_SKILLS)
                expected[GEMINI_SKILLS / relative] = source.read_bytes()
    return expected


def actual_files(root: Path) -> set[Path]:
    if not root.exists() and not root.is_symlink():
        return set()
    return {path for path in root.rglob("*") if path.is_symlink() or path.is_file()}


def _display_path(path: Path, root: Path) -> Path:
    return path.relative_to(ROOT) if path.is_relative_to(ROOT) else path.relative_to(root)


def check_tree(expected: dict[Path, bytes], root: Path, label: str) -> list[str]:
    problems: list[str] = []
    if root.is_symlink():
        return [f"unexpected symlink directory {label}: {_display_path(root, root.parent)}"]
    actual = actual_files(root)
    expected_paths = set(expected)
    for missing in sorted(expected_paths - actual):
        problems.append(f"missing {label}: {_display_path(missing, root)}")
    for extra in sorted(actual - expected_paths):
        prefix = "unexpected symlink" if extra.is_symlink() else "unexpected"
        problems.append(f"{prefix} {label}: {_display_path(extra, root)}")
    for path in sorted(actual & expected_paths):
        if path.is_symlink():
            problems.append(f"unexpected symlink {label}: {_display_path(path, root)}")
        elif path.read_bytes() != expected[path]:
            problems.append(f"stale {label}: {_display_path(path, root)}")
    return problems


def remove_unexpected(root: Path, expected_paths: set[Path]) -> None:
    for path in sorted(actual_files(root) - expected_paths, reverse=True):
        path.unlink()
    if root.exists() and not root.is_symlink():
        for directory in sorted(
            (path for path in root.rglob("*") if path.is_dir() and not path.is_symlink()),
            key=lambda path: len(path.parts),
            reverse=True,
        ):
            try:
                directory.rmdir()
            except OSError:
                pass


def atomic_write(path: Path, content: bytes) -> None:
    """Atomically write bytes to path, replacing regular files or symlinks."""
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{path.name}.", dir=path.parent
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(content)
        temporary.replace(path)
    finally:
        if temporary.exists():
            temporary.unlink()


def synchronize() -> None:
    gemini_agents = expected_agents()
    antigravity_agents = expected_antigravity_agents()
    skills = expected_skills()
    files_to_write = {
        **gemini_agents,
        **antigravity_agents,
        **skills,
        AGENTS_MANIFEST: expected_agents_manifest(),
    }
    for path, content in files_to_write.items():
        if path.is_symlink() or not path.exists() or path.read_bytes() != content:
            atomic_write(path, content)
    remove_unexpected(GEMINI_AGENTS, set(gemini_agents))
    remove_unexpected(ANTIGRAVITY_AGENTS, set(antigravity_agents))
    remove_unexpected(GEMINI_SKILLS, set(skills))
    print(
        f"SYNCED: {len(gemini_agents)} Gemini CLI agents, "
        f"{len(antigravity_agents)} Antigravity agents, "
        f"and {len(canonical_skill_directories())} Skills."
    )


def verify() -> int:
    problems = check_tree(expected_agents(), GEMINI_AGENTS, "Gemini CLI agent")
    problems.extend(
        check_tree(
            expected_antigravity_agents(),
            ANTIGRAVITY_AGENTS,
            "Antigravity agent",
        )
    )
    problems.extend(check_tree(expected_skills(), GEMINI_SKILLS, "Skill file"))
    expected_manifest = expected_agents_manifest()
    if AGENTS_MANIFEST.is_symlink():
        problems.append(f"unexpected symlink manifest: {AGENTS_MANIFEST.relative_to(ROOT)}")
    elif not AGENTS_MANIFEST.is_file():
        problems.append(f"missing manifest: {AGENTS_MANIFEST.relative_to(ROOT)}")
    elif AGENTS_MANIFEST.read_bytes() != expected_manifest:
        problems.append(f"stale manifest: {AGENTS_MANIFEST.relative_to(ROOT)}")
    if problems:
        for problem in problems:
            print(f"ERROR: {problem}", file=sys.stderr)
        print("Run: python scripts/gemini_adapter.py", file=sys.stderr)
        return 1
    print(
        f"PASS: Gemini adapter matches {len(canonical_agent_files())} canonical agents "
        f"and {len(canonical_skill_directories())} canonical Skills."
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify without writing")
    args = parser.parse_args()
    if args.check:
        return verify()
    synchronize()
    return verify()


if __name__ == "__main__":
    raise SystemExit(main())
